"""Build junbi/backend.js from My Trip's Apps Script backend (Code.gs).
The trip logic is reused as it is; storage, sign-in, files and AI calls are replaced by
browser versions: each trip is one JSON file in the user's own Google Drive, the AI key is the user's own."""
import re, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
junbi = pathlib.Path(__file__).resolve().parents[1]
src = (root / 'my-trip/apps-script/Code.gs').read_text()
lines = src.split('\n')
# drop the Apps Script HTTP entry points (doGet/doPost/json_)
start = src.index('const ACTIONS = {')
core = src[:src.index('function doGet()')] + src[start:]

def fn(name):
    m = re.search(r'^(async )?function ' + re.escape(name) + r'\b', core, re.M)
    assert m, name
    i = m.start(); depth = 0; j = core.index('{', i)
    k = j
    while True:
        c = core[k]
        if c == '{': depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0: break
        k += 1
    # replacePlan_ style "{ return withLock_(() => { ... }); }" ends after the outer brace
    return core[i:k+1]

def asyncify(text, extra=()):
    text = re.sub(r'^function ', 'async function ', text, count=1)
    for c in ['callGemini_(', 'callGeminiMany_(', 'resolveMapLink_(', 'travelLookup_(', 'geocode_('] + list(extra):
        text = re.sub(r'(?<![\w.])(?<!function )' + re.escape(c), 'await ' + c, text)
    return text

over = []
over.append(asyncify(fn('readBooking_')).replace("if (provider === 'claude') text = await callClaude_(props, prompt, files);\n  else if (provider === 'openai') text = await callOpenAI_(props, prompt, files);\n  else ", ''))
pj = fn('planJob_').replace('const plan = fn(req);', 'const plan = await fn(req);')
over.append(asyncify(pj))
pr = asyncify(fn('planReviewRun_'))
old = "const raws = await callGeminiMany_(c.props, prompts, busy).map((text, i) => { try { return parseJson_(text); } catch (e) {\n    try { return parseJson_(await callGemini_(c.props, prompts[i], [], Object.assign({ temperature: 0.4, thinking: 'low', maxTokens: 16384 }, busy))); } catch (e2) { return { days: [] }; } } });"
assert old in pr, 'planReview tail'
pr = pr.replace(old, "const texts = await callGeminiMany_(c.props, prompts, busy), raws = [];\n  for (let i = 0; i < texts.length; i++) { try { raws.push(parseJson_(texts[i])); } catch (e) {\n    try { raws.push(parseJson_(await callGemini_(c.props, prompts[i], [], Object.assign({ temperature: 0.4, thinking: 'low', maxTokens: 16384 }, busy)))); } catch (e2) { raws.push({ days: [] }); } } }")
over.append(pr)
over.append(asyncify(fn('recommendIdeasRun_')))
rp = fn('replacePlan_')
a = rp.index('  // A single range write'); b = rp.index('  return {items:next')
rp = rp[:a] + "  deleteWhere_(ITEMS, r => r.tripId === id);\n  next.forEach(it => upsert_(ITEMS, it.id, id, it));\n  if(req.operation)upsert_('plan_operations',id+':'+String(req.operation).slice(0,80),id,{snapshot:snapshot.id,resultRevision:planRevision_(next)});\n" + rp[b:]
over.append(rp)
over.append(asyncify(fn('localize_')))
over.append(asyncify(fn('sosInfo_')))
shim = (junbi / 'tools/backend-shim.js').read_text()
tail = (junbi / 'tools/backend-browser.js').read_text()
out = ('/* Junbi backend — generated by tools/build-backend.py. Do not edit by hand.\n'
       '   The trip rules come from My Trip (apps-script/Code.gs); storage is the user\'s own Google Drive. */\n'
       '(function(){\n"use strict";\n' + shim + '\n/* ---- trip rules from Code.gs ---- */\n' + core +
       '\n/* ---- async versions of the AI steps (they wait for Gemini in the browser) ---- */\n' + '\n'.join(over) +
       '\n' + tail + '\n})();\n')
(junbi / 'backend.js').write_text(out)
print('backend.js', len(out))
